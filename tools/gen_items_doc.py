#!/usr/bin/env python3
"""Пишет docs/ITEMS.md (геймдизайн предметов) из data/items.json."""
import json
d = json.load(open('data/items.json', encoding='utf8')); I = {i['id']: i for i in d['items']}
used = {k: [i for i in d['items'] if k in i.get('from', [])] for k in I}
nm = lambda k: I[k]['name']
L = ['# Предметы и рецепты', '', 'Файл собирается из `data/items.json` скриптом `tools/gen_items_doc.py`. Правь json, а не этот файл.', '',
'## Как играется', '',
'Бесконечный забег. Глюки идут справа волнами, каждая волна сильнее. Вован и Димон с крыльца швыряют на поле хлам из хаты: раз в несколько секунд в свободную клетку левой половины поля падает случайный базовый предмет. Игрок не покупает оборону, а перетаскивает предметы и сливает их друг с другом.', '',
'- **Перетащить** предмет на пустую клетку — переставить.',
'- **Одинаковые** одной звезды — тот же предмет на звезду выше, до ★3. Звезда даёт больше урона, скорости и радиуса.',
'- **Разные из рецепта** — новый предмет. Звезда результата — меньшая из двух, поэтому выгодно сначала прокачать обе половинки.',
'- **Несочетаемые** — просто меняются местами.',
'- **Кубик D20** — редкий джокер: +1 звезда любому предмету, на «критической двадцатке» (1 из 20) сразу +2. D20 на D20 — случайный предмет второго уровня.',
'- Глюки грызут предметы так же, как раньше грызли оборону. Сгрызенный предмет исчезает.',
'- **Лампочки** падают с чипсов, с убитых глюков и с неба. На них покупается «Порыться в хате» — ещё один случайный базовый предмет, цена растёт.',
'- Пылесосы в каждом ряду — последний шанс, как раньше. Глюк дошёл до крыльца — забег окончен.', '',
'## Рогалик', '',
'- **Волны бесконечны.** С каждой волной глюков больше, они толще и быстрее, в пул добавляются новые виды.',
'- **Каждые 5 волн — выбор одной из трёх «вписок»** (перков) на весь забег. Например: «Чипсы дают +1 лампочку», «Все дымовые предметы замедляют на 20% сильнее», «Вован швыряет хлам вдвое чаще», «Первое слияние каждой волны даёт +1 звезду», «D20 падает в три раза чаще».',
'- **Каждые 10 волн — босс:** кракен, Дракула со свитой и т.д.',
'- **Книга рецептов** открывается между забегами: рецепт виден, только когда его хоть раз собрал. Секретные предметы не подсвечиваются вообще.',
'- В конце забега — счёт: волна, убитые глюки, лучшие собранные предметы.', '',
'## Почему это не цепочка от А до Я', '',
'- Каждый базовый предмет входит в 3–4 рецепта. Батарейка и плакат — в четыре, поэтому они самые ценные и самые спорные: куда пустить.',
'- Каждый предмет второго уровня ведёт в 2–3 разных предмета третьего уровня. Лава-лампа может стать кальяном, диско-шаром или тесла-лампой; робот — мехой, голограммой или танком.',
'- Роли разные: стрелки, стены, ловушки, ауры, экономика, призыв, массовый контроль. Хорошая оборона — это сочетание, а не один самый сильный предмет. Аура лава-лампы бесполезна без соседей, а голограмма спасает только если рядом есть чем бить.',
'- Звезда результата — минимальная из двух, поэтому есть выбор: собрать новый предмет сейчас на ★1 или сначала прокачать половинки и получить его сразу на ★2–★3.',
'- Секреты собираются из двух предметов третьего уровня — это долгая цель на поздние волны.', '']
for t, title in ((0, 'Базовые предметы'), (1, 'Второй уровень'), (2, 'Третий уровень'), (3, 'Секретные')):
    L += [f'## {title}', '', '| Предмет | Из чего | Роль | Что делает | Ведёт в |', '|---|---|---|---|---|']
    for i in [x for x in d['items'] if x['tier'] == t]:
        frm = ' + '.join(nm(f) for f in i.get('from', [])) or ('редкий' if i.get('rare') else 'падает на поле')
        nxt = ', '.join(x['name'] for x in used[i['id']]) or '—'
        L.append(f"| **{i['name']}** | {frm} | {i['role']} | {i['effect']} | {nxt} |")
    L.append('')
L += ['## Дерево', '', '```mermaid', 'graph LR']
for i in d['items']:
    for f in i.get('from', []): L.append(f'  {f}["{nm(f)}"] --> {i["id"]}["{i["name"]}"]')
L += ['```', '']
open('docs/ITEMS.md', 'w', encoding='utf8').write('\n'.join(L)); print('ok')
